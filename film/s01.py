def osc(t0, t1, period, a, b, start=None):
    """Keys that swing between a and b (sweeping, clapping, pulling)."""
    ks = [(t0, start if start is not None else a)]; t = t0 + period / 2; i = 0
    while t < t1: ks.append((t, b if i % 2 == 0 else a)); t += period / 2; i += 1
    return ks

